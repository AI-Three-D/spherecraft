import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const temporary = mkdtempSync(join(tmpdir(), 'spherecraft-types-'));
const check = process.argv.includes('--check');
try {
    execFileSync(process.execPath, [join(root, 'node_modules/typescript/bin/tsc'),
        '--project', join(root, 'tsconfig.declarations.json'), '--outDir', temporary], { cwd: root, stdio: 'inherit' });
    for (const file of ['core/renderer/Renderer.d.ts', 'core/renderer/terrain/TerrainModule.d.ts']) {
        const content = '// Generated by npm run types:build from checked JavaScript.\n' + readFileSync(join(temporary, file), 'utf8');
        if (check) {
            if (readFileSync(join(root, file), 'utf8') !== content) throw new Error(`${file} is stale. Run npm run types:build.`);
        } else {
            writeFileSync(join(root, file), content);
        }
    }
} finally {
    rmSync(temporary, { recursive: true, force: true });
}
