// Writes core/renderer/volumetricClouds/neural/lightingModels.js from trained models in tools/neural/models.
//   node tools/neural/exportModels.mjs --default r5 r4:ms=<file>,sky=<file> 'r5:ms=<file>,sky=<file>,direct=<a>|<b>|<c>'
// Each set is selectable at runtime with volumetricClouds.settings.neuralLightingModel.
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const args = process.argv.slice(2);
const defaultIndex = args.indexOf('--default');
const fallback = defaultIndex >= 0 ? args.splice(defaultIndex, 2)[1] : null;
const roles = { ms: 'msTarget', sky: 'skyTotal', direct: 'T' };
const sets = {};
for (const arg of args) {
    const [name, list] = arg.split(':');
    sets[name] = {};
    for (const entry of list.split(',')) {
        const [role, files] = entry.split('=');
        if (!roles[role]) throw new Error(`Unknown role ${role}`);
        // file1|file2|... is an ensemble: the shader averages the members' log outputs.
        const members = await Promise.all(files.split('|').map(async file => {
            const model = JSON.parse(await fs.readFile(path.join('tools/neural/models', file), 'utf8'));
            if (model.target !== roles[role]) throw new Error(`${file} predicts ${model.target}, not ${roles[role]}`);
            const { sizes, W, b, mean, scale, outBias, features, target } = model;
            return { source: file, sizes, W, b, mean, scale, outBias, features, target };
        }));
        sets[name][role] = members.length === 1 ? members[0] : members;
    }
}
const defaultSet = fallback ?? Object.keys(sets).at(-1);
if (!sets[defaultSet]) throw new Error(`No set named ${defaultSet}`);
const round = value => Array.isArray(value) ? value.map(round)
    : typeof value === 'number' ? Number(value.toPrecision(8))
        : value && typeof value === 'object' ? Object.fromEntries(Object.entries(value).map(([k, v]) => [k, round(v)])) : value;
const body = Object.entries(sets).map(([name, set]) => `    ${name}: {\n` + Object.entries(set).map(([role, model]) =>
    `        // tools/neural/models/${[model].flat().map(m => m.source).join(' + ')}\n        ${role}: ${JSON.stringify(round(model))},`).join('\n') + '\n    },').join('\n');
const code = `// Generated by tools/neural/exportModels.mjs. Trained by the neural lab; see NEURAL_CLOUD_LAB_FINDINGS.md.
// ms: multiple scattering, sky: sky light, direct: sun transmittance to the voxel (all baked per cache voxel).
export const LIGHTING_MODEL_SETS = {
${body}
};
export const DEFAULT_LIGHTING_MODEL = '${defaultSet}';
export const multipleScatteringModel = LIGHTING_MODEL_SETS[DEFAULT_LIGHTING_MODEL].ms;
export const skyScatteringModel = LIGHTING_MODEL_SETS[DEFAULT_LIGHTING_MODEL].sky;
`;
await fs.writeFile('core/renderer/volumetricClouds/neural/lightingModels.js', code);
console.log(`lightingModels.js: ${Object.keys(sets).join(', ')} (default ${defaultSet}), ${code.length} bytes`);
