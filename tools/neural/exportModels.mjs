// Writes core/renderer/volumetricClouds/neural/lightingModels.js from trained models in tools/neural/models.
//   node tools/neural/exportModels.mjs ms=<file> sky=<file> 'direct=<a>|<b>|<c>'
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const roles = { ms: 'msTarget', sky: 'skyTotal', direct: 'T' };
const models = {};
for (const entry of process.argv.slice(2)) {
    const [role, files] = entry.split('=');
    if (!roles[role]) throw new Error(`Unknown role ${role}`);
    // file1|file2|... is an ensemble: the shader averages the members' log outputs.
    const members = await Promise.all(files.split('|').map(async file => {
        const model = JSON.parse(await fs.readFile(path.join('tools/neural/models', file), 'utf8'));
        if (model.target !== roles[role]) throw new Error(`${file} predicts ${model.target}, not ${roles[role]}`);
        const { sizes, W, b, mean, scale, outBias, features, target } = model;
        return { source: file, sizes, W, b, mean, scale, outBias, features, target };
    }));
    models[role] = members.length === 1 ? members[0] : members;
}
for (const role of Object.keys(roles)) if (!models[role]) throw new Error(`No model for ${role}`);
const round = value => Array.isArray(value) ? value.map(round)
    : typeof value === 'number' ? Number(value.toPrecision(8))
        : value && typeof value === 'object' ? Object.fromEntries(Object.entries(value).map(([k, v]) => [k, round(v)])) : value;
const body = Object.entries(models).map(([role, model]) =>
    `    // tools/neural/models/${[model].flat().map(m => m.source).join(' + ')}\n    ${role}: ${JSON.stringify(round(model))},`).join('\n');
const code = `// Generated by tools/neural/exportModels.mjs. Trained by the neural lab; see NEURAL_CLOUD_LAB_FINDINGS.md.
// ms: multiple scattering, sky: sky light, direct: sun transmittance to the voxel (all baked per cache voxel).
export const LIGHTING_MODELS = {
${body}
};
`;
await fs.writeFile('core/renderer/volumetricClouds/neural/lightingModels.js', code);
console.log(`lightingModels.js: ${Object.values(models).flat().map(m => m.source).join(', ')}, ${code.length} bytes`);
