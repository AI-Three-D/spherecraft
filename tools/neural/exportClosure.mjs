// Writes the density closure as WGSL: node tools/neural/exportClosure.mjs tools/neural/models/closure-6-4-4.json <out.js>
import fs from 'node:fs/promises';
import process from 'node:process';

const [file, out] = process.argv.slice(2);
const { sizes, W, b, mean, scale, outBias, features } = JSON.parse(await fs.readFile(file, 'utf8'));
const hidden = sizes.slice(1, -1);
if (hidden.some(n => n % 4)) throw new Error('Hidden layers must be multiples of 4');
const lit = v => { const s = Number(v).toPrecision(6); return /[.e]/.test(s) ? s : `${s}.0`; };
const vec = a => `vec4f(${a.map(lit).join(', ')})`;
const argument = { d: 'd', base: 'base', lf: 'lf', localH: 'localH', h: 'h', stratiform: 'stratiform' };
const lines = features.map((f, i) => `    let x${i} = (${argument[f]} - ${lit(mean[i])}) * ${lit(scale[i])};`);
let inputs = features.map((_, i) => `x${i}`);
W.slice(0, -1).forEach((matrix, layer) => {
    const packs = [];
    for (let p = 0; p < hidden[layer]; p += 4) {
        const terms = inputs.map((name, i) => `${vec([0, 1, 2, 3].map(k => matrix[i][p + k]))} * ${name}`);
        lines.push(`    let z${layer}_${p} = ${vec(b[layer].slice(p, p + 4))} + ${terms.join(' + ')};`);
        lines.push(`    let h${layer}_${p} = z${layer}_${p} / (vec4f(1.0) + abs(z${layer}_${p}));`);
        packs.push(...['x', 'y', 'z', 'w'].map(c => `h${layer}_${p}.${c}`));
    }
    inputs = packs;
});
const last = W.at(-1);
const sums = [];
for (let p = 0; p < inputs.length; p += 4) sums.push(`dot(${vec([0, 1, 2, 3].map(k => last[p + k][0]))}, ${inputs[p].split('.')[0]})`);
lines.push(`    return min(exp(clamp(${sums.join(' + ')} + ${lit(b.at(-1)[0] + outBias[0])}, -30.0, 2.0)), 1.0);`);
const params = W.reduce((n, m) => n + m.length * m[0].length, 0) + b.reduce((n, v) => n + v.length, 0);
await fs.writeFile(out, `// Generated by tools/neural/exportClosure.mjs from ${file.split('/').at(-1)} (${params} parameters).
// Average density of the full-detail cloud over one march interval and pixel, given the filtered sample:
// d after and base before detail erosion, lf = log2(footprint / 60 m), height in the cloud and the layer,
// and the deck share. Filtering the noise before its thresholds made clouds 1.4x too dense at 3-10 km and
// 4-12x beyond 10 km.
export const CLOUD_DENSITY_CLOSURE_WGSL = /* wgsl */\`
fn densityClosure(d: f32, base: f32, lf: f32, localH: f32, h: f32, stratiform: f32) -> f32 {
${lines.join('\n')}
}
\`;
`);
console.log(`${out}: ${params} parameters`);
